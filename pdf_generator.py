from fpdf import FPDF
from datetime import datetime
import sqlite3
import pandas as pd


class HydroReport(FPDF):
    def header(self):
        self.set_fill_color(30, 136, 229)
        self.rect(0, 0, 210, 25, "F")
        self.set_font("Helvetica", "B", 18)
        self.set_text_color(255, 255, 255)
        self.set_y(8)
        self.cell(0, 10, "Hydro Decision AI - Water Management Report", 0, 1, "C")
        self.set_text_color(0, 0, 0)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Generated by Hydro Decision AI | Page {self.page_no()}", 0, 0, "C")


def generate_pdf(region: str, action_plan: str) -> bytes:
    conn = sqlite3.connect("hydro_data.db")
    wells_df = pd.read_sql_query("SELECT * FROM wells WHERE region = ?", conn, params=(region,))
    sat_df = pd.read_sql_query("SELECT * FROM satellite_data WHERE region = ?", conn, params=(region,))
    agr_df = pd.read_sql_query("SELECT * FROM agriculture WHERE region = ?", conn, params=(region,))
    conn.close()

    pdf = HydroReport()
    pdf.add_page()

    # Section 1: Report Info
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 136, 229)
    pdf.cell(0, 8, "1. Report Information", 0, 1, "L")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(50, 7, "Region:", 0, 0, "L")
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, region, 0, 1, "L")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(50, 7, "Date:", 0, 0, "L")
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, datetime.now().strftime("%Y-%m-%d %H:%M"), 0, 1, "L")
    pdf.ln(3)

    # Section 2: Risk Assessment
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 136, 229)
    pdf.cell(0, 8, "2. Risk Assessment", 0, 1, "L")

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_fill_color(230, 240, 250)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(70, 8, "Indicator", 1, 0, "L", True)
    pdf.cell(50, 8, "Value", 1, 0, "C", True)
    pdf.cell(50, 8, "Status", 1, 1, "C", True)

    drought_risk = sat_df["drought_risk_level"].iloc[0] if not sat_df.empty else "N/A"
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(70, 7, "Drought Risk Level", 1, 0, "L")
    pdf.cell(50, 7, str(drought_risk), 1, 0, "C")
    color = (
        (198, 40, 40) if drought_risk == "High"
        else (239, 108, 0) if drought_risk == "Medium"
        else (46, 125, 50)
    )
    pdf.set_text_color(*color)
    pdf.set_font("Helvetica", "B", 10)
    status = "CRITICAL" if drought_risk == "High" else "WARNING" if drought_risk == "Medium" else "OK"
    pdf.cell(50, 7, status, 1, 1, "C")
    pdf.set_text_color(0, 0, 0)

    fert = agr_df["fertilizer_usage_tons"].iloc[0] if not agr_df.empty else 0
    soil = agr_df["soil_type"].iloc[0] if not agr_df.empty else "N/A"
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(70, 7, "Fertilizer Usage", 1, 0, "L")
    pdf.cell(50, 7, f"{fert} tons", 1, 0, "C")
    pdf.set_text_color(198, 40, 40)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(50, 7, "HIGH" if fert > 300 else "MODERATE", 1, 1, "C")
    pdf.set_text_color(0, 0, 0)

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(70, 7, "Soil Type", 1, 0, "L")
    pdf.cell(50, 7, str(soil), 1, 0, "C")
    pdf.set_text_color(*((198, 40, 40) if soil == "Sandy" else (46, 125, 50)))
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(50, 7, "VULNERABLE" if soil == "Sandy" else "PROTECTIVE", 1, 1, "C")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)

    # Section 3: Wells
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 136, 229)
    pdf.cell(0, 8, "3. Wells Status", 0, 1, "L")

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_fill_color(230, 240, 250)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(30, 8, "Well ID", 1, 0, "C", True)
    pdf.cell(40, 8, "Water Level", 1, 0, "C", True)
    pdf.cell(40, 8, "Pump Health", 1, 0, "C", True)
    pdf.cell(60, 8, "Status", 1, 1, "C", True)

    pdf.set_font("Helvetica", "", 10)
    for _, row in wells_df.iterrows():
        pdf.cell(30, 7, str(row["well_id"]), 1, 0, "C")
        pdf.cell(40, 7, f"{row['water_level_meters']} m", 1, 0, "C")
        pdf.cell(40, 7, f"{row['pump_health_score']}/100", 1, 0, "C")
        status = "CRITICAL" if row["pump_health_score"] < 50 else "OK"
        color = (198, 40, 40) if status == "CRITICAL" else (46, 125, 50)
        pdf.set_text_color(*color)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(60, 7, status, 1, 1, "C")
        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "", 10)
    pdf.ln(3)

    # Section 4: AI Action Plan
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 136, 229)
    pdf.cell(0, 8, "4. AI-Generated Action Plan", 0, 1, "L")

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(0, 0, 0)
    clean_plan = action_plan.replace("**", "").replace("*", "").replace("#", "").strip()
    pdf.set_fill_color(245, 250, 255)
    pdf.multi_cell(0, 6, clean_plan, border=1, fill=True)
    pdf.ln(5)

    # Section 5: Disclaimer
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(128, 128, 128)
    pdf.multi_cell(
        0, 5,
        "DISCLAIMER: This report is generated by an AI Decision Support System. "
        "All strategic decisions must be approved by a certified Water Authority Manager "
        "before execution. The AI system provides recommendations only.",
    )

    return bytes(pdf.output())